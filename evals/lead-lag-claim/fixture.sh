"""Does marketing spend lead signups? Weekly data, 2 years.
Finds the lag where spend best predicts signups, then permutation-tests it."""
import numpy as np
import pandas as pd

MAX_LAG = 8
N_PERM = 2000


def lagged_corr(spend, signups, lag):
    if lag == 0:
        return np.corrcoef(spend, signups)[0, 1]
    return np.corrcoef(spend[:-lag], signups[lag:])[0, 1]


def best_lag(spend, signups):
    rs = [lagged_corr(spend, signups, k) for k in range(MAX_LAG + 1)]
    k = int(np.argmax(np.abs(rs)))
    return k, rs[k]


def permutation_p(spend, signups, lag, r_obs, seed=0):
    rng = np.random.default_rng(seed)
    hits = 0
    for _ in range(N_PERM):
        r = lagged_corr(rng.permutation(spend), signups, lag)
        hits += abs(r) >= abs(r_obs)
    return (hits + 1) / (N_PERM + 1)


def run(spend, signups):
    k, r = best_lag(spend, signups)
    return k, r, permutation_p(spend, signups, k, r)


if __name__ == "__main__":
    df = pd.read_csv("weekly.csv")
    k, r, p = run(df["spend"].to_numpy(), df["signups"].to_numpy())
    print(f"Spend leads signups by {k} weeks: r = {r:.2f}, permutation p = {p:.4f}")
SKEPTIC_EOF
